import { supabase } from '../../lib/supabase'
import type { AnalysisResult } from './history'

export type AnalyzePostResponse = {
  analysis: AnalysisResult
  model: { provider: string; name: string; version: string }
  isSample?: boolean
}

const demoSample: AnalyzePostResponse = {
  isSample: true,
  model: { provider: 'SENTINEL Demo', name: 'Illustrative sample', version: 'Not generated by Gemini' },
  analysis: {
    sentiment: { label: 'neutral', score: 0.08 },
    emotions: [
      { category: 'joy', score: 0.34 }, { category: 'sadness', score: 0.12 }, { category: 'anger', score: 0.04 }, { category: 'fear', score: 0.08 },
      { category: 'surprise', score: 0.06 }, { category: 'disgust', score: 0.02 }, { category: 'trust', score: 0.26 }, { category: 'anticipation', score: 0.08 },
    ],
    behavioralSignals: [],
    explanation: 'This example shows how SENTINEL presents cautious, text-focused language signals. It is not an analysis of the post you entered.',
    explanationEvidence: 'Example text only',
    confidence: 0.5,
    suggestions: ['Consider the wording in its broader context.', 'Reach out to a trusted person if you would like support.'],
    caveat: 'Illustrative sample only. This result was not generated from your text and is not a diagnosis.',
  },
}

export async function analyzePost(text: string, platform: string, demoMode = false): Promise<AnalyzePostResponse> {
  let accessToken: string | undefined
  if (!demoMode) {
    if (!supabase) throw new Error('SENTINEL is not connected to Supabase. Sign in again after configuration is complete.')
    const { data, error } = await supabase.auth.getSession()
    if (error || !data.session?.access_token) throw new Error('Your session has expired. Sign in again before analyzing a post.')
    accessToken = data.session.access_token
  }

  let response: Response
  try {
    response = await fetch(demoMode ? '/api/demo-analyze' : '/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', ...(accessToken ? { Authorization: `Bearer ${accessToken}` } : {}) },
      body: JSON.stringify({ text, platform }),
    })
  } catch {
    if (demoMode) return demoSample
    throw new Error('The analysis service could not be reached. Run the app with Vercel development mode and try again.')
  }

  const payload: unknown = await response.json().catch(() => null)
  if (demoMode && !response.headers.get('content-type')?.includes('application/json')) return demoSample
  if (!response.ok) {
    if (demoMode && [404, 429, 500, 502, 503, 504].includes(response.status)) return demoSample
    const message = payload && typeof payload === 'object' && 'error' in payload && typeof payload.error === 'object' && payload.error && 'message' in payload.error && typeof payload.error.message === 'string'
      ? payload.error.message
      : 'Analysis failed. Please try again.'
    throw new Error(message)
  }
  if (!payload || typeof payload !== 'object' || !('analysis' in payload) || !('model' in payload)) {
    if (demoMode) return demoSample
    throw new Error('The analysis service returned an invalid response. No result was saved.')
  }
  return payload as AnalyzePostResponse
}
